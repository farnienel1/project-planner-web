/** The workbook bytes. The spreadsheet library (xlsx) is loaded only here, when a workbook is made. */
export async function buildWeeklyReportXlsx(data: WeeklyReportData): Promise<ArrayBuffer> {
  const XLSX = await import('xlsx')
  const xml = buildWeeklyReportSpreadsheetXml(data)
  const parsed = XLSX.read(xml, { type: 'string' })
  return XLSX.write(parsed, { bookType: 'xlsx', type: 'array' }) as ArrayBuffer
}

export async function downloadWeeklyReportWorkbook(data: WeeklyReportData, filename: string): Promise<void> {
  const bytes = await buildWeeklyReportXlsx(data)
  const blob = new Blob([bytes], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename.endsWith('.xlsx') ? filename : `${filename}.xlsx`
  link.click()
  URL.revokeObjectURL(url)
}

function downloadTextFile(contents: string, filename: string, mime: string): void {
  const blob = new Blob([contents], { type: mime })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  link.click()
  URL.revokeObjectURL(url)
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function spreadsheetRow(cells: string[]): string {
  return `<Row>${cells
    .map((cell) => `<Cell><Data ss:Type="String">${escapeXml(neutralizeSpreadsheetFormula(cell))}</Data></Cell>`)
    .join('')}</Row>`
}

function spreadsheetTable(headers: string[], rows: string[][]): string {
  const body = rows.length === 0 ? [spreadsheetRow(headers.map(() => ''))] : rows.map((row) => spreadsheetRow(row))
  return `${spreadsheetRow(headers)}${body.join('')}`
}

/** Excel SpreadsheetML matching the iOS weekly report sections and columns. */
export function buildWeeklyReportSpreadsheetXml(data: WeeklyReportData): string {
  const periodLabel = formatReportPeriodLabel(data.reportPeriod.start, data.reportPeriod.end)
  const generatedLabel = weeklyReportGeneratedLabel(data)
  // Rulebook 1.51.0 (Q4f): the Excel download is kept (owner decision) and shows the same rows as the screen and PDF.
  const body = weeklyReportSections(data)
    .map((section) =>
      [
        spreadsheetRow([section.title]),
        spreadsheetTable(section.headers, section.rows.length ? section.rows : [[section.empty, ...section.headers.slice(1).map(() => '')]]),
        section.note ? spreadsheetRow([section.note]) : '',
        spreadsheetRow(['']),
      ].join('')
    )
    .join('')

  return `<?xml version="1.0"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:o="urn:schemas-microsoft-com:office:office"
 xmlns:x="urn:schemas-microsoft-com:office:excel"
 xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet">
 <Worksheet ss:Name="Weekly Report">
  <Table>
   ${spreadsheetRow(['PROJECT PLANNER'])}
   ${spreadsheetRow([data.organizationName])}
   ${spreadsheetRow(['WEEKLY REPORT'])}
   ${spreadsheetRow(['Period', periodLabel])}
   ${spreadsheetRow(['Invoicing period', data.invoicingPeriodLabel])}
   ${spreadsheetRow(['Generated', generatedLabel])}
   ${spreadsheetRow([''])}
   ${body}
  </Table>
 </Worksheet>
</Workbook>`
}

export function printWeeklyReport(html: string): void {
  const frame = document.createElement('iframe')
  frame.setAttribute('aria-hidden', 'true')
  frame.style.position = 'fixed'
  frame.style.right = '0'
  frame.style.bottom = '0'
  frame.style.width = '0'
  frame.style.height = '0'
  frame.style.border = '0'
  document.body.appendChild(frame)
  const doc = frame.contentDocument
  const win = frame.contentWindow
  if (!doc || !win) {
    frame.remove()
    return
  }
  doc.open()
  doc.write(html)
  doc.close()
  window.setTimeout(() => {
    win.focus()
    win.print()
    window.setTimeout(() => frame.remove(), 1000)
  }, 200)
}
