function escapeXml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

function unescapeXml(value: string): string {
  return value
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
}

function styledCell(value: string, style: string, mergeAcross = 0): string {
  const merge = mergeAcross > 0 ? ` ss:MergeAcross="${mergeAcross}"` : ''
  return `<Cell ss:StyleID="${style}"${merge}><Data ss:Type="String">${escapeXml(value)}</Data></Cell>`
}

function row(cells: string[], height?: number): string {
  const h = height ? ` ss:Height="${height}"` : ''
  return `<Row${h}>${cells.join('')}</Row>`
}

