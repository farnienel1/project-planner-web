export function spreadsheetRowsFromXml(xml: string): string[][] {
  const rows: string[][] = []
  const rowMatches = xml.match(/<Row\b[^>]*>[\s\S]*?<\/Row>/g) || []
  for (const block of rowMatches) {
    const cells = [...block.matchAll(/<Data\b[^>]*>([\s\S]*?)<\/Data>/g)].map((match) =>
      unescapeXml(match[1].replace(/\s+/g, ' ').trim())
    )
    rows.push(cells)
  }
  return rows
}

function label(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, ' ')
}

export function parseBlankTalkRows(rows: string[][]): BlankTalkFields | null {
  const fields: BlankTalkFields = {
    title: '',
    category: '',
    trades: '',
    project: '',
    weekCommencing: '',
    presentedBy: '',
    purpose: '',
    keyPoints: [],
  }
  let purposeNext = false
  const purposeLines: string[] = []
  for (const cells of rows) {
    const a = label(cells[0] || '')
    const b = (cells[1] || '').trim()
    if (a === 'title') {
      fields.title = b
      purposeNext = false
      continue
    }
    if (a === 'category') {
      fields.category = b
      const tradesIndex = cells.findIndex((cell) => label(cell) === 'trades')
      if (tradesIndex >= 0) fields.trades = (cells[tradesIndex + 1] || '').trim()
      continue
    }
    if (a === 'project') {
      fields.project = b
      const weekIndex = cells.findIndex((cell) => label(cell) === 'week commencing')
      if (weekIndex >= 0) fields.weekCommencing = (cells[weekIndex + 1] || '').trim()
      const presentedIndex = cells.findIndex((cell) => label(cell) === 'presented by')
      if (presentedIndex >= 0) fields.presentedBy = (cells[presentedIndex + 1] || '').trim()
      continue
    }
    if (a === 'purpose') {
      purposeNext = true
      if (b) purposeLines.push(b)
      continue
    }
    if (a === 'key control points' || a === 'references' || a === 'attendee sign-off' || a === 'name') {
      purposeNext = false
    }
    if (purposeNext && (cells[0] || '').trim() && a !== 'key control points') {
      purposeLines.push((cells[0] || '').trim())
    }
    if (a.startsWith('key point')) {
      const point = b || (cells[2] || '').trim()
      if (point) fields.keyPoints.push(point)
    }
  }
  fields.purpose = purposeLines.join('\n').trim()
  const recognised = Boolean(fields.title || fields.purpose || fields.keyPoints.length || fields.category)
  return recognised ? fields : null
}

export function parseBlankTalkWorkbookXml(xml: string): BlankTalkFields | null {
  if (!xml.includes('<Workbook')) return null
  return parseBlankTalkRows(spreadsheetRowsFromXml(xml))
}

export async function readBlankTalkFile(file: File): Promise<BlankTalkFields | null> {
  const name = file.name.toLowerCase()
  const buffer = await file.arrayBuffer()
  const asText = new TextDecoder().decode(buffer)
  if (asText.includes('<Workbook')) return parseBlankTalkWorkbookXml(asText)
  if (!name.endsWith('.xlsx') && !name.endsWith('.xls') && !asText.startsWith('PK')) return null
  const XLSX = await import('xlsx')
  const book = XLSX.read(buffer, { type: 'array' })
  const sheet = book.Sheets[book.SheetNames[0]]
  if (!sheet) return null
  const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, raw: false, defval: '' }) as string[][]
  return parseBlankTalkRows(rows.map((row) => row.map((cell) => String(cell ?? ''))))
}

export function downloadBlankTalkExcel(): void {
  const blob = new Blob([blankTalkWorkbookXml()], { type: 'application/vnd.ms-excel' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = 'toolbox-talk-blank.xls'
  document.body.appendChild(link)
  link.click()
  link.remove()
  window.setTimeout(() => URL.revokeObjectURL(url), 1500)
}
